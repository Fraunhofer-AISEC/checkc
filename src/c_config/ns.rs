pub fn ns_get_owner_user_ns(pid: libc::pid_t, ns_type: Type) -> Result<Id> {
    let path = format!("/proc/{pid}/ns/{}", ns_type.to_string());
    let path = PathBuf::from(path);

    let f_ns = File::open(path)?;
    let fd = f_ns.into_raw_fd();

    let owner_fd = unsafe { libc::ioctl(fd, NS_GET_USERNS) };
    if owner_fd == -1 {
        let errno = Errno::last();

        // special case: user namespace
        if errno == Errno::EPERM && ns_type == Type::User {
            let id = Id::from_fd(fd)?;
            let _ = unsafe { File::from_raw_fd(fd) };

            return Ok(id);
        }
        return Err(Error::IoctlFailed(errno));
    }

    let user_ns = unsafe { File::from_raw_fd(owner_fd) };
    let metadata = user_ns.metadata().unwrap();

    // claim ownership
    let _ = unsafe { File::from_raw_fd(fd) };

    Ok(Id {
        st_dev: metadata.st_dev(),
        st_ino: metadata.st_ino(),
    })
}

// returns list of (parent id, namespace id) for user or pid namespace of given process
pub fn ns_get_parent_ns(pid: libc::pid_t, ns_type: Type) -> Result<Vec<(Id, Id)>> {
    let path = format!("/proc/{pid}/ns/{}", ns_type.to_string());
    let path = PathBuf::from(path);
    let mut result = Vec::new();

    let f_ns = File::open(path)?;
    let mut fd = f_ns.into_raw_fd();
    let mut id = Id::from_fd(fd)?;

    let mut parent_fd = unsafe { libc::ioctl(fd, NS_GET_PARENT) };
    while parent_fd != -1 {
        let parent_id = Id::from_fd(parent_fd)?;

        result.push((parent_id, id));

        // recurse in next layer
        id = parent_id;
        // claim ownership of not longer needed fd
        let _ = unsafe { File::from_raw_fd(fd) };
        fd = parent_fd;
        // get parent of parent
        parent_fd = unsafe { libc::ioctl(fd, NS_GET_PARENT) };
    }

    // no new parent found
    match Errno::last() {
        // EPERM indicates initial namespace
        nix::errno::Errno::EPERM => result.push((id, id)),
        errno => return Err(Error::IoctlFailed(errno)),
    }

    // claim ownership
    let _ = unsafe { File::from_raw_fd(fd) };

    Ok(result)
}

pub fn ns_config(init_pid: libc::pid_t, c_init_pid: libc::pid_t) -> Result<Config> {
    let mut proto_ns_config = Config::default();

    // parse namespaces
    log::info!(
        "Collecting namespace config for host PID {init_pid} and container PID {c_init_pid}"
    );
    let ns_set_init = Info::parse_proc_ns(init_pid)?;
    let ns_set_c_init = Info::parse_proc_ns(c_init_pid)?;

    log::debug!("Computing shared namespaces between container and host");
    proto_ns_config.shared_host = ns_set_c_init
        .intersection(&ns_set_init)
        .map(|info| info.to_owned())
        .collect();

    log::debug!("Computing container namespaces not shared with host");
    proto_ns_config.unshared = ns_set_c_init
        .iter()
        .filter(|ns| !ns_set_init.contains(ns))
        .map(|info| info.to_owned())
        .collect();

    log::debug!("Computing hierarchies of user and pid namespaces");
    let user_hierarchy = internal::Hierarchy::user_ns_hierarchy()?;
    let pid_hierarchy = internal::Hierarchy::pid_ns_hierarchy()?;

    proto_ns_config.user_ns_hierarchy = Some(Hierarchy::from(user_hierarchy));
    proto_ns_config.pid_ns_hierarchy = Some(Hierarchy::from(pid_hierarchy));

    Ok(proto_ns_config)
}
