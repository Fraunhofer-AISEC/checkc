        fn create_hierarchy(ns_type: Type) -> Result<Hierarchy> {
            let proc_dir = std::fs::read_dir("/proc")?;

            // read proc and filter for PID-directories
            let pids: Vec<PathBuf> = proc_dir
                .filter(std::result::Result::is_ok)
                .map(|entry| {
                    let entry = entry.unwrap();
                    entry.path()
                })
                .filter(|entry| entry.is_dir())
                .filter(|entry| {
                    entry
                        .to_str()
                        .unwrap()
                        .contains(|char: char| char.is_ascii_digit())
                })
                .collect();

            let pids = pids.iter().map(|entry| {
                entry
                    .file_name()
                    .unwrap()
                    .to_str()
                    .unwrap()
                    .parse::<libc::pid_t>()
                    .unwrap()
            });

            // for each pid get ns id and corresponding parent ns id
            let id_map: Vec<(Id, Id)> = pids
                .map(|pid| super::ns_get_parent_ns(pid, ns_type))
                .filter(Result::is_ok)
                .map(Result::unwrap)
                .flatten()
                .collect();
            // Identity mapping should be initial namespace
            let (root, _) = id_map
                .iter()
                .filter(|(p_id, id)| p_id == id)
                .next()
                .unwrap()
                .clone();

            let mut hierarchy = Self::new(root);
            hierarchy.populate(&id_map);

            Ok(hierarchy)
        }

        fn populate(&mut self, id_map: &[(Id, Id)]) {
            // remove parent_id from children
            let id_map_filtered: Vec<(Id, Id)> = id_map
                .iter()
                .copied()
                .filter(|(_, id)| id != &self.parent_id)
                .collect();

            // get children from map
            if !id_map_filtered.is_empty() {
                let mut children = HashSet::new();
                id_map_filtered
                    .iter()
                    .filter(|(parent_id, _)| parent_id == &self.parent_id)
                    .map(|mapping| mapping.1.to_owned())
                    .map(Self::new)
                    .for_each(|child| {
                        children.insert(child);
                    });

                // populate children
                let children = children
                    .drain()
                    .map(|mut child| {
                        child.populate(&id_map_filtered);
                        child
                    })
                    .collect();

                self.children = children;
            }
        }

